function addClientPromocodes(clientCode, startingId, isActive) {
  const values = [0, 5, 10];
  const generated = values.map((value, index) => ({
    id: `PRIVATE-${startingId + index}`,
    code: `${clientCode}${String(value).padStart(2, "0")}`,
    type: "percentage",
    value: value,
    isActive: isActive,
    startDate: "2025-01-01",
    endDate: "2028-12-31",
    isPublic: true,
    usageLimit: 1,
    usedBy: [],
    maxDiscountPercentage: 15,
    minOrderAmount: 10,
  }));

  PrivatePromocodes.push(...generated);
}

